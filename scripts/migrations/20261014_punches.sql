-- Hours Commander v2: punch-based time tracking.
-- A day is a list of punches paired in order (in, out, in, out...), so any
-- number of breaks per day is supported. Rows are owned by a Supabase Auth
-- user and protected by RLS; the legacy tables are left untouched.

create table if not exists public.punches (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  punched_at timestamptz not null,
  -- Workday the punch belongs to; differs from the local date of punched_at
  -- only for shifts that cross midnight.
  work_date date not null,
  source text not null default 'manual'
    check (source in ('manual', 'solides', 'csv', 'ocr', 'legacy')),
  -- Id from the upstream system (e.g. "<solides interval id>:start"), used to
  -- upsert instead of duplicating when a punch is adjusted upstream.
  external_id text,
  note text,
  created_at timestamptz not null default now(),
  constraint punches_user_punched_at_unique unique (user_id, punched_at),
  constraint punches_user_external_unique unique (user_id, source, external_id)
);

create index if not exists idx_punches_user_work_date
  on public.punches (user_id, work_date);

create table if not exists public.work_days (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  work_date date not null,
  is_holiday boolean not null default false,
  work_mode text check (work_mode in ('home_office', 'presencial')),
  note text,
  updated_at timestamptz not null default now(),
  primary key (user_id, work_date)
);

create table if not exists public.user_settings (
  user_id uuid primary key default auth.uid() references auth.users (id) on delete cascade,
  day_target_minutes integer not null default 480
    check (day_target_minutes between 0 and 1440),
  timezone text not null default 'America/Sao_Paulo',
  valor_base numeric not null default 0,
  valor_hora numeric not null default 0,
  valor_bonus numeric not null default 0,
  valor_aux_transporte numeric not null default 0,
  pix_key text,
  solides_last_sync_at timestamptz,
  updated_at timestamptz not null default now()
);

alter table public.punches enable row level security;
alter table public.work_days enable row level security;
alter table public.user_settings enable row level security;

drop policy if exists punches_owner on public.punches;
create policy punches_owner on public.punches
  for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

drop policy if exists work_days_owner on public.work_days;
create policy work_days_owner on public.work_days
  for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

drop policy if exists user_settings_owner on public.user_settings;
create policy user_settings_owner on public.user_settings
  for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));
